export function toBanglaDigits(num: number | string): string {
  const map: Record<string, string> = {
    '0': '০',
    '1': '১',
    '2': '২',
    '3': '৩',
    '4': '৪',
    '5': '৫',
    '6': '৬',
    '7': '৭',
    '8': '৮',
    '9': '৯',
  };
  return String(num).replace(/[0-9]/g, (d) => map[d] || d);
}

export function formatMoney(amount: number, currency: 'BDT' | 'USD' = 'BDT'): string {
  const formatted = amount.toLocaleString('en-IN');
  return currency === 'USD' ? `$${toBanglaDigits(formatted)}` : `৳${toBanglaDigits(formatted)}`;
}

